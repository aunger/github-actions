class TestStripBylines(unittest.TestCase):
    def test_strips_single_byline(self):
        text = "Some text\nhttps://claude.ai/code/session_abc123"
        self.assertEqual(ssb.strip_bylines(text), "Some text")

    def test_strips_byline_mid_text(self):
        text = "Before\nhttps://claude.ai/code/session_xyz\nAfter"
        self.assertEqual(ssb.strip_bylines(text), "Before\nAfter")

    def test_strips_multiple_bylines(self):
        text = (
            "Line one\nhttps://claude.ai/code/session_aaa\n"
            "Line two\nhttps://claude.ai/code/session_bbb"
        )
        self.assertEqual(ssb.strip_bylines(text), "Line one\nLine two")

    def test_unchanged_when_no_byline(self):
        text = "Just a normal comment with no byline."
        self.assertEqual(ssb.strip_bylines(text), text)

    def test_unchanged_for_partial_url(self):
        # A URL without the session_ prefix must not be touched.
        text = "See https://claude.ai/code/other_thing for details."
        self.assertEqual(ssb.strip_bylines(text), text)

    def test_requires_leading_newline(self):
        # The byline must be preceded by a newline to be stripped.
        text = "https://claude.ai/code/session_abc123 is mentioned inline"
        self.assertEqual(ssb.strip_bylines(text), text)

    def test_strips_byline_with_long_token(self):
        token = "session_" + "a" * 50
        text = f"Final line\nhttps://claude.ai/code/{token}"
        self.assertEqual(ssb.strip_bylines(text), "Final line")

    def test_empty_string_unchanged(self):
        self.assertEqual(ssb.strip_bylines(""), "")

    def test_strips_markdown_link_footer(self):
        # The form Claude agents actually emit (no separator line).
        text = "PR body\n_Generated by [Claude Code](https://claude.ai/code/session_abc123)_"
        self.assertEqual(ssb.strip_bylines(text), "PR body")

    def test_strips_markdown_link_footer_with_separator(self):
        # Footer preceded by a --- separator line (common agent pattern).
        text = "PR body\n---\n_Generated by [Claude Code](https://claude.ai/code/session_xyz789)_"
        self.assertEqual(ssb.strip_bylines(text), "PR body")

    def test_strips_markdown_link_footer_mid_text(self):
        # Footer followed by more text (separator consumed, trailing text preserved).
        text = "Before\n_Generated by [Claude Code](https://claude.ai/code/session_q)_\nAfter"
        self.assertEqual(ssb.strip_bylines(text), "Before\nAfter")

    def test_unchanged_for_markdown_link_without_session_prefix(self):
        # A [Claude Code] link not preceded by a newline should not be stripped,
        # regardless of whether the URL carries a session_ suffix.
        text = "See _Generated by [Claude Code](https://claude.ai/code)_ for info."
        self.assertEqual(ssb.strip_bylines(text), text)

    def test_strips_markdown_link_footer_without_session_suffix(self):
        # The [Claude Code] link points at https://claude.ai/code with no
        # /session_<token> suffix.
        text = "PR body\n_Generated by [Claude Code](https://claude.ai/code)_"
        self.assertEqual(ssb.strip_bylines(text), "PR body")

    def test_strips_markdown_link_footer_without_session_suffix_with_separator(self):
        # Same as above, but with the --- separator agents commonly append.
        text = (
            "Decision: Changes requested.\n"
            "\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
        )
        self.assertEqual(ssb.strip_bylines(text), "Decision: Changes requested.\n")

    def test_strips_both_bare_url_and_markdown_footer(self):
        # A body containing both forms has both stripped.
        text = (
            "Line one\nhttps://claude.ai/code/session_aaa\n"
            "Line two\n_Generated by [Claude Code](https://claude.ai/code/session_bbb)_"
        )
        self.assertEqual(ssb.strip_bylines(text), "Line one\nLine two")


def empty_response():
    """A urlopen_https mock whose response has an empty body, as a PATCH/PUT may.

    The test classes that send requests take it as a class decorator, so each
    test method receives it as mock_open.
    """
    mock = MagicMock()
    mock.return_value.__enter__.return_value.read.return_value = b""
    return mock


def sent(mock_open):
    """Return the method, URL and body of the one request *mock_open* received."""
    mock_open.assert_called_once()
    args, kwargs = mock_open.call_args
    return kwargs["method"], args[0], json.loads(args[1])["body"]


@patch("github_api.urlopen_https", new_callable=empty_response)
class TestUpdate(unittest.TestCase):
    def test_sends_json_with_the_github_headers(self, mock_open):
        self.assertTrue(ssb._update("PATCH", "tok", "repos/o/r/issues/1", "text"))
        args, kwargs = mock_open.call_args
        self.assertEqual(args[0], "https://api.github.com/repos/o/r/issues/1")
        self.assertEqual(kwargs["headers"]["Authorization"], "Bearer tok")
        self.assertEqual(kwargs["headers"]["Content-Type"], "application/json")
        self.assertEqual(kwargs["method"], "PATCH")

    def test_an_unreadable_success_response_still_counts(self, mock_open):
        # A 2xx whose echoed object is not JSON: the write was applied.
        mock_open.return_value.__enter__.return_value.read.return_value = b"{trunc"
        self.assertTrue(ssb._update("PATCH", "tok", "repos/o/r/issues/1", "text"))

    def test_an_http_error_returns_false(self, mock_open):
        mock_open.side_effect = urllib.error.HTTPError("u", 404, "Not Found", {}, None)
        self.assertFalse(ssb._update("PUT", "tok", "repos/o/r/x", "text"))


@patch("github_api.urlopen_https", new_callable=empty_response)
class TestFetchBody(unittest.TestCase):
    def test_returns_the_body(self, mock_open):
        mock_open.return_value.__enter__.return_value.read.return_value = b'{"body": "hi"}'
        self.assertEqual(ssb._fetch_body("tok", "x"), "hi")
        args, kwargs = mock_open.call_args
        self.assertEqual(args[0], "https://api.github.com/x")
        self.assertEqual(kwargs["method"], "GET")
        self.assertEqual(kwargs["headers"]["Authorization"], "Bearer tok")

    def test_a_null_body_is_empty(self, mock_open):
        mock_open.return_value.__enter__.return_value.read.return_value = b'{"body": null}'
        self.assertEqual(ssb._fetch_body("tok", "x"), "")

    def test_an_error_returns_none(self, mock_open):
        mock_open.side_effect = urllib.error.HTTPError("u", 404, "Not Found", {}, None)
        self.assertIsNone(ssb._fetch_body("tok", "x"))


