#!/usr/bin/env python3
"""strip_session_bylines.py: Remove Claude session-URL bylines from GitHub content.

Scans a piece of text for Claude session-URL bylines and strips each
occurrence so the surrounding text reads cleanly.
Two forms are matched:

    \nhttps://claude.ai/code/session_<token>          (bare URL)
    \n_Generated by [Claude Code](https://claude.ai/code[/session_<token>])_
                                                       (Markdown-link footer)

The Markdown-link footer's URL may end at "code" or continue with a
"/session_<token>" suffix; both are stripped, since agents have emitted
both forms.

An optional \n--- separator preceding the Markdown-link footer is consumed
along with it so no orphaned "---" is left behind.
The body that is stripped is fetched fresh from the API, not taken from the
event payload, so a late run cannot write back text older than a later edit.
If the content is unchanged after stripping, no update is sent.

The strip-session-bylines action runs this module, with github_api.py,
github_headers.py, https_only.py and session_bylines.py from ../shared.
It runs from the action's own pinned copy and checks nothing out. On the three
pull request events that is no boundary: the calling workflow comes from the
pull request's merge ref, so a pull request can change what the job runs.
The action handles five event types (pull_request_target is handled as
pull_request):

  - issues [opened, edited]:                       issue body
  - issue_comment [created, edited]:               comments on issues and PRs
  - pull_request [opened, edited]:                 PR body
  - pull_request_review_comment [created, edited]: PR diff-line comments
  - pull_request_review [submitted, edited]:       PR review body

Manual mode: when STRIP_NUMBER names an issue or pull request, the event is
ignored and the whole item is cleaned instead: its description, every issue
comment and, for a pull request, every diff-line review comment and every
review body.  Each list is read page by page, and only items whose body
changes are written.  This is for bylines written before the workflow existed
or missed by it, from a workflow_dispatch run, whose payload names no item.

Usage:
    python3 strip_session_bylines.py

Environment variables (the action sets GITHUB_TOKEN; the runner sets the rest):
    GITHUB_TOKEN          GitHub token with issues:write and pull-requests:write.
    GITHUB_REPOSITORY     "owner/repo".
    GITHUB_EVENT_NAME     One of: issues, issue_comment, pull_request,
                          pull_request_target, pull_request_review_comment,
                          pull_request_review.
    GITHUB_EVENT_PATH     Path to the JSON file with the full event payload.
    STRIP_NUMBER          Optional issue or PR number; selects manual mode, which
                          needs only GITHUB_TOKEN and GITHUB_REPOSITORY.

In event mode the exit code is always 0, so a missing/failed strip never breaks
the caller.  Manual mode is run by a person, who needs to see a failure: it exits
1 if the number is not a positive integer or any read or write fails.
"""

import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "shared"))

from github_api import gh_api
from github_headers import github_headers
from https_only import urlopen_https
from session_bylines import strip_bylines

# The byline pattern and strip_bylines() live in session_bylines.py, whose
# docstring names the write-time checker that carries a copy of them.
# strip_bylines is re-exported here so that callers and tests reach it through
# this module.


def _update(method: str, token: str, url: str, body: str) -> bool:
    """Update *url* with {"body": body} using the specified HTTP method.

    Args:
        method: HTTP method name ("patch" or "put").
        token: GitHub API token.
        url: API endpoint URL.
        body: The new body text.

    Returns:
        True if the request succeeded, False otherwise.
    """
    headers = {**github_headers(token), "Content-Type": "application/json"}
    data = json.dumps({"body": body}).encode()
    try:
        # urlopen raises HTTPError for any status outside 2xx.
        with urlopen_https(url, data, headers=headers, method=method.upper(), timeout=30):
            pass
        return True
    except Exception as exc:  # noqa: BLE001
        print(f"Warning: {method.upper()} {url} failed: {exc}", file=sys.stderr)
        return False


def _patch(token: str, url: str, body: str) -> bool:
    """PATCH *url* with {"body": body}; return True on success."""
    return _update("patch", token, url, body)


def _put(token: str, url: str, body: str) -> bool:
    """PUT *url* with {"body": body}; return True on success."""
    return _update("put", token, url, body)


def _fetch_body(token: str, url: str) -> str | None:
    """GET *url* and return its "body" field ("" if empty), or None on failure."""
    try:
        with urlopen_https(url, headers=github_headers(token), method="GET", timeout=30) as response:
            return json.loads(response.read()).get("body") or ""
    except Exception as exc:  # noqa: BLE001
        print(f"Warning: GET {url} failed: {exc}", file=sys.stderr)
        return None


def _strip(token: str, url: str, method: str, label: str, payload_body: str | None) -> bool:
    """Strip bylines from the item at *url*.  Returns True if an update was issued.

    The payload's body only decides whether to look further: an event whose
    body carries no byline needs no API call.  The body that is stripped and
    written back is the one fetched from *url*, because the payload's copy can
    be older than the stored one: a run for an item's creation that finishes
    after the run for its edit would otherwise write the older text back.
    """
    payload_body = payload_body or ""
    if strip_bylines(payload_body) == payload_body:
        print(f"{label}: no bylines found, skipping.")
        return False

    current = _fetch_body(token, url)
    if current is None:
        return False
    stripped = strip_bylines(current)
    if stripped == current:
        print(f"{label}: no bylines in the current body, skipping.")
        return False

    ok = _update(method, token, url, stripped)
    if ok:
        print(f"{label}: bylines stripped.")
    return ok


def handle_issue(token: str, repository: str, payload: dict) -> bool:
    """Strip bylines from an issue body.  Returns True if a PATCH was issued."""
    issue = payload.get("issue", {})
    number = issue.get("number")
    url = f"https://api.github.com/repos/{repository}/issues/{number}"
    return _strip(token, url, "patch", f"Issue #{number}", issue.get("body"))


def handle_issue_comment(token: str, repository: str, payload: dict) -> bool:
    """Strip bylines from an issue/PR comment.  Returns True if a PATCH was issued."""
    comment = payload.get("comment", {})
    comment_id = comment.get("id")
    url = f"https://api.github.com/repos/{repository}/issues/comments/{comment_id}"
    return _strip(token, url, "patch", f"Comment #{comment_id}", comment.get("body"))


def handle_pull_request(token: str, repository: str, payload: dict) -> bool:
    """Strip bylines from a PR body.  Returns True if a PATCH was issued."""
    pr = payload.get("pull_request", {})
    number = pr.get("number")
    url = f"https://api.github.com/repos/{repository}/pulls/{number}"
    return _strip(token, url, "patch", f"PR #{number}", pr.get("body"))


def handle_pull_request_review_comment(token: str, repository: str, payload: dict) -> bool:
    """Strip bylines from a PR review comment.  Returns True if a PATCH was issued."""
    comment = payload.get("comment", {})
    comment_id = comment.get("id")
    url = f"https://api.github.com/repos/{repository}/pulls/comments/{comment_id}"
    return _strip(token, url, "patch", f"Review comment #{comment_id}", comment.get("body"))


def handle_pull_request_review(token: str, repository: str, payload: dict) -> bool:
    """Strip bylines from a PR review body.  Returns True if a PUT was issued."""
    review = payload.get("review", {})
    pr_number = payload.get("pull_request", {}).get("number")
    review_id = review.get("id")
    url = f"https://api.github.com/repos/{repository}/pulls/{pr_number}/reviews/{review_id}"
    return _strip(token, url, "put", f"Review #{review_id}", review.get("body"))


# ---------------------------------------------------------------------------
# Manual mode: one whole issue or pull request
# ---------------------------------------------------------------------------

PER_PAGE = 100


def _pages(path: str, token: str) -> list[dict]:
    """GET every page of the list at *path* (which has no query string yet).

    A page shorter than PER_PAGE is the last one.
    Raises what gh_api raises.
    """
    items: list[dict] = []
    page = 1
    while True:
        batch = gh_api(f"{path}?per_page={PER_PAGE}&page={page}", token) or []
        items.extend(batch)
        if len(batch) < PER_PAGE:
            return items
        page += 1


def _strip_current(token: str, url: str, method: str, label: str, body: str | None) -> bool:
    """Write *body* back to *url* without its bylines, if it has any.

    Returns False only if a write was needed and failed.
    *body* was just read from the API, so it is not fetched again.
    """
    body = body or ""
    stripped = strip_bylines(body)
    if stripped == body:
        return True
    ok = _update(method, token, url, stripped)
    if ok:
        print(f"{label}: bylines stripped.")
    return ok


def strip_whole_item(token: str, repository: str, number: int) -> bool:
    """Strip bylines from issue or PR *number* and everything written on it.

    Returns True if every read and every needed write succeeded.
    """
    api = f"https://api.github.com/repos/{repository}"
    try:
        issue = gh_api(f"repos/{repository}/issues/{number}", token)
        # The issues endpoint serves pull requests too, marked by this key.
        is_pr = "pull_request" in issue
        comments = _pages(f"repos/{repository}/issues/{number}/comments", token)
        review_comments = (
            _pages(f"repos/{repository}/pulls/{number}/comments", token) if is_pr else []
        )
        reviews = _pages(f"repos/{repository}/pulls/{number}/reviews", token) if is_pr else []
    except Exception as exc:  # noqa: BLE001
        print(f"Error: could not read #{number}: {exc}", file=sys.stderr)
        return False

    kind = "PR" if is_pr else "Issue"
    print(
        f"{kind} #{number}: {len(comments)} comments"
        + (f", {len(review_comments)} review comments, {len(reviews)} reviews" if is_pr else "")
        + "."
    )

    targets = [
        (
            f"{api}/pulls/{number}" if is_pr else f"{api}/issues/{number}",
            "patch",
            f"{kind} #{number}",
            issue.get("body"),
        )
    ]
    targets += [
        (f"{api}/issues/comments/{c['id']}", "patch", f"Comment #{c['id']}", c.get("body"))
        for c in comments
    ]
    targets += [
        (f"{api}/pulls/comments/{c['id']}", "patch", f"Review comment #{c['id']}", c.get("body"))
        for c in review_comments
    ]
    targets += [
        (f"{api}/pulls/{number}/reviews/{r['id']}", "put", f"Review #{r['id']}", r.get("body"))
        for r in reviews
        if r.get("body")  # A review with no body has nothing to strip.
    ]

    ok = True
    for url, method, label, body in targets:
        ok = _strip_current(token, url, method, label, body) and ok
    return ok


_HANDLER_NAMES = {
    "issues": "handle_issue",
    "issue_comment": "handle_issue_comment",
    "pull_request": "handle_pull_request",
    "pull_request_target": "handle_pull_request",
    "pull_request_review_comment": "handle_pull_request_review_comment",
    "pull_request_review": "handle_pull_request_review",
}


def main(argv: list[str] | None = None) -> int:
    del argv  # No CLI arguments; configuration is entirely from the environment.

    token = os.environ.get("GITHUB_TOKEN", "")
    repository = os.environ.get("GITHUB_REPOSITORY", "")
    event_name = os.environ.get("GITHUB_EVENT_NAME", "")
    event_path = os.environ.get("GITHUB_EVENT_PATH", "")
    number = os.environ.get("STRIP_NUMBER", "").strip()

    if not token:
        print("GITHUB_TOKEN not set--skipping.", file=sys.stderr)
        return 1 if number else 0
    if not repository:
        print("GITHUB_REPOSITORY not set--skipping.", file=sys.stderr)
        return 1 if number else 0

    if number:
        # isdecimal() alone would accept "0" and non-ASCII digits.
        if not (number.isascii() and number.isdecimal() and int(number) > 0):
            print(f"Error: STRIP_NUMBER {number!r} is not an issue or PR number.", file=sys.stderr)
            return 1
        return 0 if strip_whole_item(token, repository, int(number)) else 1

    if not event_name:
        print("GITHUB_EVENT_NAME not set--skipping.", file=sys.stderr)
        return 0
    if not event_path:
        print("GITHUB_EVENT_PATH not set--skipping.", file=sys.stderr)
        return 0

    handler_name = _HANDLER_NAMES.get(event_name)
    if handler_name is None:
        print(f"Unsupported event '{event_name}'--skipping.", file=sys.stderr)
        return 0
    handler = globals()[handler_name]

    try:
        with open(event_path, encoding="utf-8") as fh:
            payload = json.load(fh)
    except Exception as exc:  # noqa: BLE001
        print(f"Warning: could not read event payload at '{event_path}': {exc}", file=sys.stderr)
        return 0

    handler(token, repository, payload)
    return 0


if __name__ == "__main__":
    sys.exit(main())
